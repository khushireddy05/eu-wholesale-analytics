def _write_cell(ws, row: int, col: int, value: Any, fmt, text_fmt) -> None:
    if value is None or (isinstance(value, float) and np.isnan(value)):
        ws.write_blank(row, col, None, fmt)
    elif isinstance(value, (np.integer,)):
        ws.write_number(row, col, int(value), fmt)
    elif isinstance(value, (np.floating, float)):
        ws.write_number(row, col, float(value), fmt)
    elif isinstance(value, (np.bool_, bool)):
        ws.write_string(row, col, "Yes" if bool(value) else "No", text_fmt)
    elif isinstance(value, (pd.Timestamp, datetime)):
        ws.write_datetime(row, col, value, fmt)
    else:
        ws.write_string(row, col, str(value), text_fmt)


def _humanise(name: str) -> str:
    special = {
        "eur": "EUR", "pct": "%", "eur_m": "EUR m", "yoy": "YoY", "mom": "MoM",
        "kpi": "KPI", "id": "ID", "wape": "WAPE", "mape": "MAPE",
        "smape": "sMAPE", "mae": "MAE", "rmse": "RMSE", "r12m": "R12M",
        "hhi": "HHI", "nrr": "NRR", "lo": "Low", "hi": "High", "cagr": "CAGR",
    }
    words = []
    for i, part in enumerate(name.split("_")):
        key = part.lower()
        if key in special:
            words.append(special[key])
        else:
            words.append(part.capitalize() if i == 0 else part.lower())
    return " ".join(words)


def _auto_width(series: pd.Series, column: str) -> int:
    header = len(_humanise(column))
    try:
        longest = int(series.astype(str).str.len().max() or 0)
    except Exception:
        longest = 0
    return int(min(max(header + 3, longest + 2, 10), 42))


def _a1(row: int, col: int) -> str:
    from xlsxwriter.utility import xl_rowcol_to_cell
    return xl_rowcol_to_cell(row, col)


def sheet_range(sheet: str, first_row: int, first_col: int,
                last_row: int, last_col: int) -> list:
    """Chart series reference: ``[sheet, r1, c1, r2, c2]``."""
    return [sheet, first_row, first_col, last_row, last_col]


def eur_m(df: pd.DataFrame, cols: Iterable[str]) -> pd.DataFrame:
    """Rescale EUR columns to millions and rename them accordingly."""
    out = df.copy()
    for c in cols:
        if c in out.columns:
            out[c] = out[c] / 1e6
            out = out.rename(columns={c: c.replace("_eur", "_eur_m")})
    return out

